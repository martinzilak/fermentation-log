export type MessageKey = keyof typeof en;

/** Looks up a string and fills `{name}` placeholders. */
export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return en[key].replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}

export const statusLabel = (s: BatchStatus) => t(`status.${s}`);
export const stepTypeLabel = (s: StepType) => t(`stepType.${s}`);
export const kindLabel = (k: Kind) => t(`kind.${k}`);
export const eventLabel = (e: EventType) => t(`event.${e}`);
